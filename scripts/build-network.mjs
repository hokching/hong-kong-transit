// Builds the station list and line order from MTR open data.
// Coordinates are not included: the browser reads those from the Lands Department.

const SOURCE = "https://opendata.mtr.com.hk/data/mtr_lines_and_stations.csv"

const LINES = [
  { code: "ISL", nameZh: "港島綫", color: "#0071ce" },
  { code: "TWL", nameZh: "荃灣綫", color: "#e2231a" },
  { code: "KTL", nameZh: "觀塘綫", color: "#1b9431" },
  { code: "TKL", nameZh: "將軍澳綫", color: "#6b2089" },
  { code: "EAL", nameZh: "東鐵綫", color: "#3aa0dc" },
  { code: "TML", nameZh: "屯馬綫", color: "#923011" },
  { code: "TCL", nameZh: "東涌綫", color: "#f7941d" },
  { code: "AEL", nameZh: "機場快綫", color: "#1c7670" },
  { code: "SIL", nameZh: "南港島綫", color: "#b5bd00" },
  { code: "DRL", nameZh: "迪士尼綫", color: "#e777cb" },
]

const response = await fetch(SOURCE, {
  headers: { "User-Agent": "hk-traffic-map/1.0" },
})
if (!response.ok) {
  throw new Error(`MTR station list HTTP ${response.status}`)
}
const text = (await response.text()).replace(/^\uFEFF/, "")
const table = parseCsv(text)
const header = table[0]
const column = Object.fromEntries(header.map((name, index) => [name, index]))

const rows = []
for (const record of table.slice(1)) {
  const line = (record[column["Line Code"]] ?? "").trim()
  const direction = (record[column.Direction] ?? "").trim()
  const code = (record[column["Station Code"]] ?? "").trim()
  const nameZh = (record[column["Chinese Name"]] ?? "").trim()
  const nameEn = (record[column["English Name"]] ?? "").trim()
  const sequenceText = (record[column.Sequence] ?? "").trim()
  if (!line || !code || !direction) continue
  rows.push({
    line,
    direction,
    code,
    nameZh,
    nameEn,
    sequence: Number(sequenceText),
  })
}

const stations = new Map()
const lines = []

for (const meta of LINES) {
  const lineRows = rows.filter((row) => row.line === meta.code)
  const directions = new Map()
  for (const row of lineRows) {
    const list = directions.get(row.direction) ?? []
    list.push(row)
    directions.set(row.direction, list)
    const existing = stations.get(row.code) ?? {
      code: row.code,
      nameZh: officialChineseName(row.nameZh),
      nameEn: row.nameEn,
      lines: [],
    }
    if (!existing.lines.includes(meta.code)) existing.lines.push(meta.code)
    stations.set(row.code, existing)
  }

  const paths = []
  for (const list of directions.values()) {
    const ordered = list
      .slice()
      .sort((a, b) => a.sequence - b.sequence)
      .map((row) => row.code)
    paths.push(ordered)
  }
  const drawn = uniqueUndirected(paths)
  lines.push({
    ...meta,
    paths: meta.code === "EAL" ? withRacecourse(drawn) : drawn,
  })
}

if (!stations.has("RAC")) {
  stations.set("RAC", {
    code: "RAC",
    nameZh: "馬場",
    nameEn: "Racecourse",
    lines: ["EAL"],
  })
}

const stationList = [...stations.values()].sort((a, b) =>
  a.nameZh.localeCompare(b.nameZh, "zh-HK"),
)

assertNetwork(stationList, lines)

const generated = `// Generated by scripts/build-network.mjs. Do not edit by hand.
// Station names and line order: ${SOURCE}
// Racecourse is not in that file. It is included because the next-train API serves it.
// On race days it replaces Fo Tan between Sha Tin and University, so it is drawn
// as a parallel path rather than inserted into the everyday line.

export type StationRecord = {
  code: string
  nameZh: string
  nameEn: string
  lines: string[]
}

export type LineRecord = {
  code: string
  nameZh: string
  color: string
  paths: string[][]
}

export const stations: StationRecord[] = ${JSON.stringify(stationList, null, 2)}

export const lines: LineRecord[] = ${JSON.stringify(lines, null, 2)}
`

await import("node:fs/promises").then((fs) =>
  fs.writeFile(new URL("../src/data/mtr-network.ts", import.meta.url), generated),
)

console.log(`stations ${stationList.length}`)
