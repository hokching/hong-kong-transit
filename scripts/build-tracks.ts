function pointOf(place: StationPlace): Point {
  return [place.lon, place.lat]
}

async function loadPlaces(): Promise<StationPlace[]> {
  const response = await fetch(VENUE_URL)
  if (!response.ok) throw new Error(`Lands Department HTTP ${response.status}`)
  const matched = matchVenues(await response.json())
  if (matched.missing.length > 0) {
    throw new Error(`Missing station coordinates: ${matched.missing.join(", ")}`)
  }
  return matched.places
}

async function loadTileTemplate(): Promise<string> {
  const response = await fetch(TILEJSON_URL)
  if (!response.ok) throw new Error(`OpenFreeMap tile JSON HTTP ${response.status}`)
  const tilejson = (await response.json()) as { tiles?: string[] }
  const template = tilejson.tiles?.[0]
  if (!template) throw new Error("OpenFreeMap tile JSON has no tiles")
  return template
}

async function loadRailGraph(template: string): Promise<GraphNode[]> {
  const tiles = tileRange()
  console.log(`reading ${tiles.length} railway tiles`)
  const nodes: GraphNode[] = []
  const index = new Map<string, number>()
  let cursor = 0
  async function worker() {
    for (;;) {
      const tile = tiles[cursor]
      cursor += 1
      if (!tile) return
      const url = template.replace("{z}", String(tile.z)).replace("{x}", String(tile.x)).replace("{y}", String(tile.y))
      const response = await fetch(url)
      if (!response.ok) throw new Error(`Tile HTTP ${response.status} ${url}`)
      const tileData = new VectorTile(new Pbf(Buffer.from(await response.arrayBuffer())))
      const layer = tileData.layers.transportation
      if (!layer) continue
      for (let featureIndex = 0; featureIndex < layer.length; featureIndex += 1) {
        const feature = layer.feature(featureIndex)
        if (!isPassengerRail(feature.properties)) continue
        for (const ring of feature.loadGeometry()) {
          const points = ring.map((point) => project(tile, point.x, point.y, layer.extent))
          addLine(nodes, index, points)
        }
      }
    }
  }
  await Promise.all(Array.from({ length: 8 }, () => worker()))
  return nodes
}

function isPassengerRail(properties: Record<string, unknown>): boolean {
  if (properties.service === "yard") return false
  const kind = `${properties.class}|${properties.subclass}`
  return kind === "transit|subway" || kind === "rail|rail"
}

function project(tile: { z: number; x: number; y: number }, px: number, py: number, extent: number): Point {
  const world = 2 ** tile.z
  const lon = ((tile.x + px / extent) / world) * 360 - 180
  const mercatorY = (tile.y + py / extent) / world
  const lat = (Math.atan(Math.sinh(Math.PI * (1 - 2 * mercatorY))) * 180) / Math.PI
  return [round(lon, 6), round(lat, 6)]
}

function addLine(nodes: GraphNode[], index: Map<string, number>, points: Point[]) {
  let previous = -1
  let previousPoint: Point | null = null
  for (const point of points) {
    const id = nodeId(nodes, index, point)
    if (previous >= 0 && previous !== id && previousPoint) {
      const length = distanceMeters(previousPoint, point)
      if (length > 0) {
        nodes[previous].edges.push({ to: id, points: [previousPoint, point], length })
        nodes[id].edges.push({ to: previous, points: [point, previousPoint], length })
      }
    }
    previous = id
    previousPoint = point
  }
}

function nodeId(nodes: GraphNode[], index: Map<string, number>, point: Point): number {
  const key = `${point[0]},${point[1]}`
  const existing = index.get(key)
  if (existing !== undefined) return existing
  const id = nodes.length
  nodes.push({ lon: point[0], lat: point[1], edges: [] })
  index.set(key, id)
  return id
}

function stitchEndpoints(nodes: GraphNode[]) {
  const cell = 0.0005
  const grid = new Map<string, number[]>()
  for (let id = 0; id < nodes.length; id += 1) {
    const key = cellKey(nodes[id].lon, nodes[id].lat, cell)
    const list = grid.get(key) ?? []
    list.push(id)
    grid.set(key, list)
  }
  for (let id = 0; id < nodes.length; id += 1) {
    if (nodes[id].edges.length !== 1) continue
    const node = nodes[id]
    const linked = new Set(node.edges.map((edge) => edge.to))
    const cx = Math.floor(node.lon / cell)
    const cy = Math.floor(node.lat / cell)
    let best = -1
    let bestDistance = STITCH_METERS
    for (let dx = -1; dx <= 1; dx += 1) {
      for (let dy = -1; dy <= 1; dy += 1) {
        for (const other of grid.get(`${cx + dx},${cy + dy}`) ?? []) {
          if (other === id || linked.has(other)) continue
          const distance = distanceMeters(node, nodes[other])
          if (distance > 0 && distance < bestDistance) {
            bestDistance = distance
            best = other
          }
        }
      }
    }
    if (best < 0) continue
    const other = nodes[best]
    const points: Point[] = [
      [node.lon, node.lat],
      [other.lon, other.lat],
    ]
    node.edges.push({ to: best, points, length: bestDistance })
    other.edges.push({ to: id, points: [points[1], points[0]], length: bestDistance })
  }
}

function bridgeComponents(nodes: GraphNode[], threshold: number) {
  const parent = nodes.map((_, id) => id)
  const find = (id: number): number => {
    let root = id
    while (parent[root] !== root) root = parent[root]
    let cursor = id
    while (parent[cursor] !== root) {
      const next = parent[cursor]
      parent[cursor] = root
      cursor = next
    }
    return root
  }
  const unite = (left: number, right: number) => {
    const a = find(left)
    const b = find(right)
    if (a !== b) parent[b] = a
  }
  for (let id = 0; id < nodes.length; id += 1) {
    for (const edge of nodes[id].edges) unite(id, edge.to)
  }
  const cell = threshold / 70000
  const grid = new Map<string, number[]>()
  for (let id = 0; id < nodes.length; id += 1) {
    const key = cellKey(nodes[id].lon, nodes[id].lat, cell)
    const list = grid.get(key) ?? []
    list.push(id)
    grid.set(key, list)
  }
  const bridges = new Map<string, { from: number; to: number; length: number }>()
  for (let id = 0; id < nodes.length; id += 1) {
    const node = nodes[id]
    const cx = Math.floor(node.lon / cell)
    const cy = Math.floor(node.lat / cell)
    const root = find(id)
    for (let dx = -1; dx <= 1; dx += 1) {
      for (let dy = -1; dy <= 1; dy += 1) {
        for (const other of grid.get(`${cx + dx},${cy + dy}`) ?? []) {
          if (other <= id) continue
          const otherRoot = find(other)
          if (otherRoot === root) continue
          const length = distanceMeters(node, nodes[other])
          if (length === 0 || length > threshold) continue
          const key = root < otherRoot ? `${root}:${otherRoot}` : `${otherRoot}:${root}`
          const existing = bridges.get(key)
          if (!existing || length < existing.length) bridges.set(key, { from: id, to: other, length })
        }
      }
    }
  }
  for (const bridge of bridges.values()) {
    const from = nodes[bridge.from]
    const to = nodes[bridge.to]
    const points: Point[] = [
      [from.lon, from.lat],
      [to.lon, to.lat],
    ]
    from.edges.push({ to: bridge.to, points, length: bridge.length })
    to.edges.push({ to: bridge.from, points: [points[1], points[0]], length: bridge.length })
  }
  console.log(`bridged ${bridges.size} rail gaps under ${threshold} m`)
}

function routeHop(
  nodes: GraphNode[],
  nodeIndex: NodeIndex,
  from: StationPlace,
  to: StationPlace,
): Point[] | null {
  const starts = nearbyNodes(nodeIndex, from, MAX_SNAP_METERS)
  const ends = nearbyNodes(nodeIndex, to, MAX_SNAP_METERS)
  if (starts.length === 0 || ends.length === 0) return null
  if (starts.some((id) => ends.includes(id))) return [pointOf(from), pointOf(to)]
  const direct = distanceMeters(from, to)
  const routed = shortestPath(nodes, starts, ends, from, to, 0.08) ?? shortestPath(nodes, starts, ends, from, to, 0.45)
  if (!routed) return null
  const length = polylineLength(routed)
  if (length > direct * 3.2 && length > direct + 4000) {
    console.log(`too long ${from.code}-${to.code} rail ${Math.round(length)} direct ${Math.round(direct)}`)
    return null
  }
  return routed
}

function shortestPath(
  nodes: GraphNode[],
  starts: number[],
  ends: number[],
  origin: StationPlace,
  dest: StationPlace,
  pad: number,
): Point[] | null {
  const minLon = Math.min(origin.lon, dest.lon) - pad
  const maxLon = Math.max(origin.lon, dest.lon) + pad
  const minLat = Math.min(origin.lat, dest.lat) - pad
  const maxLat = Math.max(origin.lat, dest.lat) + pad
  const targets = new Set(ends)
  const cost = new Map<number, number>()
  const previous = new Map<number, { from: number; points: Point[] }>()
  const heap = new Heap()
  for (const start of starts) {
    cost.set(start, 0)
    heap.push(0, start)
  }
  let reached = -1
  while (heap.size > 0) {
    const current = heap.pop()
    if (!current || current.cost !== cost.get(current.node)) continue
    if (targets.has(current.node)) {
      reached = current.node
      break
    }
    for (const edge of nodes[current.node].edges) {
      const nextNode = nodes[edge.to]
      if (nextNode.lon < minLon || nextNode.lon > maxLon || nextNode.lat < minLat || nextNode.lat > maxLat) {
        continue
      }
      const nextCost = current.cost + edgeWeight(edge, origin, dest)
      const known = cost.get(edge.to)
      if (known !== undefined && nextCost >= known) continue
      cost.set(edge.to, nextCost)
      previous.set(edge.to, { from: current.node, points: edge.points })
      heap.push(nextCost, edge.to)
    }
  }
  if (reached < 0) return null
  const parts: Point[][] = []
  let cursor = reached
  const seen = new Set<number>()
  while (previous.has(cursor)) {
    if (seen.has(cursor)) return null
    seen.add(cursor)
    const step = previous.get(cursor)
    if (!step) return null
    parts.push(step.points)
    cursor = step.from
  }
  parts.reverse()
  const line: Point[] = []
  for (const part of parts) appendLine(line, part)
  return line
}

function edgeWeight(edge: Edge, origin: StationPlace, dest: StationPlace): number {
  const middle = edge.points[Math.floor(edge.points.length / 2)]
  const offset = distanceToSegmentMeters(middle, pointOf(origin), pointOf(dest))
  return edge.length + Math.max(0, offset - CORRIDOR_FREE_METERS) * CORRIDOR_PENALTY
}

type NodeIndex = { cell: number; grid: Map<string, number[]>; nodes: GraphNode[] }

function indexNodes(nodes: GraphNode[]): NodeIndex {
  const cell = 0.002
  const grid = new Map<string, number[]>()
  for (let id = 0; id < nodes.length; id += 1) {
    const key = cellKey(nodes[id].lon, nodes[id].lat, cell)
    const list = grid.get(key) ?? []
    list.push(id)
    grid.set(key, list)
  }
  return { cell, grid, nodes }
}

function nearbyNodes(index: NodeIndex, place: StationPlace, maxMeters: number): number[] {
  const reach = Math.max(1, Math.ceil(maxMeters / 180))
  const cx = Math.floor(place.lon / index.cell)
  const cy = Math.floor(place.lat / index.cell)
  const found: Array<{ id: number; distance: number }> = []
  for (let dx = -reach; dx <= reach; dx += 1) {
    for (let dy = -reach; dy <= reach; dy += 1) {
      for (const id of index.grid.get(`${cx + dx},${cy + dy}`) ?? []) {
        const distance = distanceMeters(place, index.nodes[id])
        if (distance <= maxMeters) found.push({ id, distance })
      }
    }
  }
  found.sort((a, b) => a.distance - b.distance)
  return found.slice(0, 40).map((item) => item.id)
}

function appendLine(target: Point[], points: Point[]) {
  for (const point of points) {
    const last = target[target.length - 1]
    if (!last || last[0] !== point[0] || last[1] !== point[1]) target.push(point)
  }
}

function simplify(points: Point[], tolerance: number): Point[] {
  if (points.length < 3) return points.map(roundPoint)
  const keep = new Array<boolean>(points.length).fill(false)
  keep[0] = true
  keep[points.length - 1] = true
  const stack: Array<[number, number]> = [[0, points.length - 1]]
  while (stack.length > 0) {
    const [start, end] = stack.pop()!
    let farthest = -1
    let farthestDistance = 0
    for (let index = start + 1; index < end; index += 1) {
      const distance = distanceToSegmentMeters(points[index], points[start], points[end])
      if (distance > farthestDistance) {
        farthestDistance = distance
        farthest = index
      }
    }
    if (farthest >= 0 && farthestDistance > tolerance) {
      keep[farthest] = true
      stack.push([start, farthest], [farthest, end])
    }
  }
  return points.filter((_, index) => keep[index]).map(roundPoint)
}

function maxOffsetMeters(points: Point[], start: Point, end: Point): number {
  let max = 0
  for (const point of points) max = Math.max(max, distanceToSegmentMeters(point, start, end))
  return max
}

function distanceToLineMeters(point: Point, line: Point[]): number {
  let best = Infinity
  for (let index = 0; index < line.length - 1; index += 1) {
    best = Math.min(best, distanceToSegmentMeters(point, line[index], line[index + 1]))
  }
  return best
}

function polylineLength(points: Point[]): number {
  let length = 0
  for (let index = 0; index < points.length - 1; index += 1) {
    length += distanceMeters(points[index], points[index + 1])
  }
  return length
}

function distanceToSegmentMeters(point: Point, start: Point, end: Point): number {
  const scale = metersPerDegree((start[1] + end[1]) / 2)
  const ax = (end[0] - start[0]) * scale.x
  const ay = (end[1] - start[1]) * scale.y
  const lengthSquared = ax * ax + ay * ay
  if (lengthSquared === 0) return distanceMeters(point, start)
  const ratio = Math.min(
    1,
    Math.max(0, (((point[0] - start[0]) * scale.x) * ax + ((point[1] - start[1]) * scale.y) * ay) / lengthSquared),
  )
  return distanceMeters(point, [start[0] + ((end[0] - start[0]) * ratio), start[1] + ((end[1] - start[1]) * ratio)])
}

function distanceMeters(a: { lon?: number; lat?: number } | Point, b: { lon?: number; lat?: number } | Point): number {
  const first = asPoint(a)
  const second = asPoint(b)
  const earth = 6371008.8
  const lat1 = (first[1] * Math.PI) / 180
  const lat2 = (second[1] * Math.PI) / 180
  const dLat = lat2 - lat1
  const dLon = ((second[0] - first[0]) * Math.PI) / 180
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLon / 2) ** 2
  return 2 * earth * Math.asin(Math.min(1, Math.sqrt(h)))
}

function asPoint(value: { lon?: number; lat?: number } | Point): Point {
  if (Array.isArray(value)) return value
  return [value.lon ?? 0, value.lat ?? 0]
}

function metersPerDegree(lat: number): { x: number; y: number } {
  const radians = (lat * Math.PI) / 180
  return { x: 111320 * Math.cos(radians), y: 110540 }
}

function tileRange(): Array<{ z: number; x: number; y: number }> {
  const tiles = []
  const x0 = lonToTile(WEST, ZOOM)
  const x1 = lonToTile(EAST, ZOOM)
  const y0 = latToTile(NORTH, ZOOM)
  const y1 = latToTile(SOUTH, ZOOM)
  for (let x = x0; x <= x1; x += 1) {
    for (let y = y0; y <= y1; y += 1) tiles.push({ z: ZOOM, x, y })
  }
  return tiles
}

function lonToTile(lon: number, zoom: number): number {
  return Math.floor(((lon + 180) / 360) * 2 ** zoom)
}

function latToTile(lat: number, zoom: number): number {
  const radians = (lat * Math.PI) / 180
  return Math.floor(((1 - Math.log(Math.tan(radians) + 1 / Math.cos(radians)) / Math.PI) / 2) * 2 ** zoom)
}

function cellKey(lon: number, lat: number, size: number): string {
  return `${Math.floor(lon / size)},${Math.floor(lat / size)}`
}

function round(value: number, digits: number): number {
  const scale = 10 ** digits
  return Math.round(value * scale) / scale
}

function roundPoint(point: Point): Point {
  return [round(point[0], 5), round(point[1], 5)]
}
