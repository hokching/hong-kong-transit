// Builds geographically accurate MTR track curves.
// Station order stays in src/data/mtr-network.ts. Shape points come from
// OpenStreetMap railways in the OpenFreeMap vector tiles.

import { writeFile } from "node:fs/promises"
import { VectorTile } from "@mapbox/vector-tile"
import Pbf from "pbf"
import { lines } from "../src/lib/network.ts"
import { matchVenues, type StationPlace } from "../src/lib/places.ts"

const VENUE_URL =
  "https://mapapi.hkmapservice.gov.hk/ogc/wfs/indoor/mtr_venue_polygon?service=WFS&version=1.1.0&request=GetFeature&outputFormat=application%2Fjson"
const TILEJSON_URL = "https://tiles.openfreemap.org/planet"
const WEST = 113.82
const EAST = 114.42
const SOUTH = 22.18
const NORTH = 22.56
const ZOOM = 14
const MAX_SNAP_METERS = 350
const STITCH_METERS = 35
const CORRIDOR_FREE_METERS = 800
const CORRIDOR_PENALTY = 4

type Point = [number, number]
type Edge = { to: number; points: Point[]; length: number }
type GraphNode = { lon: number; lat: number; edges: Edge[] }

class Heap {
  private items: Array<{ cost: number; node: number }> = []

  get size(): number {
    return this.items.length
  }

  push(cost: number, node: number) {
    const items = this.items
    items.push({ cost, node })
    let index = items.length - 1
    while (index > 0) {
      const parent = (index - 1) >> 1
      if (items[parent].cost <= items[index].cost) break
      ;[items[parent], items[index]] = [items[index], items[parent]]
      index = parent
    }
  }

  pop(): { cost: number; node: number } | undefined {
    const items = this.items
    const top = items[0]
    const last = items.pop()
    if (!top) return undefined
    if (items.length > 0 && last) {
      items[0] = last
      let index = 0
      for (;;) {
        let smallest = index
        const left = index * 2 + 1
        const right = left + 1
        if (left < items.length && items[left].cost < items[smallest].cost) smallest = left
        if (right < items.length && items[right].cost < items[smallest].cost) smallest = right
        if (smallest === index) break
        ;[items[smallest], items[index]] = [items[index], items[smallest]]
        index = smallest
      }
    }
    return top
  }
}

const places = await loadPlaces()
const placeByCode = new Map(places.map((place) => [place.code, place]))
const tileTemplate = await loadTileTemplate()
const graph = await loadRailGraph(tileTemplate)
stitchEndpoints(graph)
bridgeComponents(graph, 260)
const nodeIndex = indexNodes(graph)
console.log(`rail graph: ${graph.length} nodes`)

const trackPaths: Record<string, Point[][][]> = {}
const problems: string[] = []
let curvedHops = 0
let fallbackHops = 0
let largestCurve = { meters: 0, label: "" }

for (const line of lines) {
  trackPaths[line.code] = line.paths.map((path, pathIndex) => {
    const coordinates: Point[] = []
    for (let index = 0; index < path.length - 1; index += 1) {
      const from = placeByCode.get(path[index])
      const to = placeByCode.get(path[index + 1])
      const label = `${line.code} ${path[index]}-${path[index + 1]}`
      if (!from || !to) {
        problems.push(`${label} is missing a station coordinate`)
        continue
      }
      const routed = routeHop(graph, nodeIndex, from, to)
      const straight = distanceMeters(from, to)
      const chosen = routed ?? [pointOf(from), pointOf(to)]
      if (routed) {
        curvedHops += 1
        const curve = maxOffsetMeters(routed, pointOf(from), pointOf(to))
        if (curve > largestCurve.meters) largestCurve = { meters: curve, label }
      } else {
        fallbackHops += 1
        problems.push(`${label} has no rail path within the corridor (${Math.round(straight)} m apart)`)
      }
      appendLine(coordinates, chosen)
    }
    for (const code of path) {
      const place = placeByCode.get(code)
      if (!place || coordinates.length < 2) continue
      const away = distanceToLineMeters(pointOf(place), coordinates)
      if (away > MAX_SNAP_METERS) {
        problems.push(`${line.code} path ${pathIndex} misses ${code} by ${Math.round(away)} m`)
      }
    }
    const simplified = simplify(coordinates, 8)
    return simplified.length >= 2 ? [simplified] : []
  })
}

